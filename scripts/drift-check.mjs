#!/usr/bin/env node
/**
 * Host'ta Generator'dan kaymış dosyaları bulur. Commit'ten önce çalıştırılır; çıkış kodu 1 = fark var.
 *
 *   node scripts/drift-check.mjs <host> [<host> …]               asset'ler: kök (backend) ve `apps/*` istemcileri
 *                                                                 (`assets-sync --check`)
 *   node scripts/drift-check.mjs <host> [<host> …] --generated   ayrıca generate çıktısı: host geçici bir kopyaya alınır,
 *                                                                 kopyada `generate`, `admin-config` ve her uygulama için
 *                                                                 `client` çalışır; G damgalı dosya host'takinden farklıysa
 *                                                                 (elle değiştirilmiş ya da Generator ilerlemiş) listelenir.
 *                                                                 Sahipsiz G dosyası da listelenir: kopyada her G dosyasının
 *                                                                 sonuna işaret satırı eklenir, asset sync + generate onu
 *                                                                 yeniden yazar; işareti kalan dosyayı Generator artık
 *                                                                 üretmiyordur (model / modül kalkmış, asset taşınmış).
 *                                                                 Gerçek host'a yazılmaz.
 *
 * Asset farkı: `assets-sync <dir> --diff` ile incelenir, Generator'a taşınır ya da `--apply` ile geri alınır.
 * Generate farkı: elle yapılan değişiklik K dosyaya / hook'a taşınır; Generator ilerlemişse host'ta generate çalıştırılır.
 * Sahipsiz dosya: kullanılmıyorsa silinir; proje hâlâ kullanıyorsa damgası kaldırılıp K yapılır.
 */
import { spawnSync } from 'child_process';
import { appendFileSync, cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync } from 'fs';
import { tmpdir } from 'os';
import { basename, dirname, join, relative, resolve } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const generated = args.includes('--generated');
const hosts = args.filter((a) => !a.startsWith('--')).map((h) => resolve(h));
if (!hosts.length) {
  console.error('Kullanım: node scripts/drift-check.mjs <host> [<host> …] [--generated]');
  process.exit(1);
}

const SKIP_DIRS = new Set(['node_modules', '.git', 'bin', 'obj', 'dist', 'build', '.venv', '__pycache__', 'logs', 'test-results', 'playwright-report', '.expo', 'ios', 'android', 'Pods']);
const G_HEADER = /^\s*(?:\/\/|#) (?:Auto Generated By Generator\b|<auto-generated by Generator \/>)[^\n]*\n/;
const SOURCE = /\.(cs|ts|tsx|py)$/;
const ORPHAN_MARK = 'drift-check: generate bu dosyayı yeniden yazmadı';

const appsOf = (host) => {
  const apps = join(host, 'apps');
  if (!existsSync(apps)) return [];
  return readdirSync(apps).map((name) => join(apps, name)).filter((dir) => statSync(dir).isDirectory() && existsSync(join(dir, 'package.json')));
};

const node = (script, scriptArgs) => spawnSync(process.execPath, [join(root, 'scripts', script), ...scriptArgs], { encoding: 'utf8' });

function checkAssets(host) {
  let failed = false;
  for (const dir of [host, ...appsOf(host)]) {
    const r = node('assets-sync.mjs', [dir, '--check']);
    const out = `${r.stdout ?? ''}${r.stderr ?? ''}`.trim();
    if (out.startsWith('Host tanınmadı')) continue;
    const label = relative(dirname(host), dir).replace(/\\/g, '/');
    console.log(`[${r.status === 0 ? 'ok' : 'FARK'}] ${label}: ${out.split('\n').join('\n    ')}`);
    if (r.status !== 0) failed = true;
  }
  return failed;
}

function sourceFiles(dir, base = dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(name)) sourceFiles(full, base, out);
    } else if (SOURCE.test(name)) {
      out.push(relative(base, full));
    }
  }
  return out;
}

const body = (text) => text.replace(/\r\n/g, '\n').replace(G_HEADER, '').trimEnd();

function checkGenerated(host) {
  const tmp = mkdtempSync(join(tmpdir(), 'drift-check-'));
  const copy = join(tmp, basename(host));
  try {
    cpSync(host, copy, { recursive: true, filter: (src) => !SKIP_DIRS.has(basename(src)) });
    const marked = sourceFiles(copy).filter((rel) => G_HEADER.test(readFileSync(join(copy, rel), 'utf8').replace(/\r\n/g, '\n')));
    for (const rel of marked) appendFileSync(join(copy, rel), `\n${rel.endsWith('.py') ? '#' : '//'} ${ORPHAN_MARK}\n`);
    const steps = [copy, ...appsOf(copy)].map((dir) => ['assets-sync.mjs', [dir, '--apply-all']]);
    steps.push(['host.mjs', ['generate', copy]]);
    if (appsOf(copy).some((a) => basename(a) === 'admin')) steps.push(['host.mjs', ['admin-config', copy]]);
    for (const app of appsOf(copy)) steps.push(['host.mjs', ['client', copy, app]]);
    for (const [script, scriptArgs] of steps) {
      const r = node(script, scriptArgs);
      if (r.status !== 0 && script !== 'assets-sync.mjs') {
        console.log(`[HATA] ${basename(host)}: ${script} ${scriptArgs[0]} ${relative(copy, scriptArgs[2] ?? copy) || '.'}\n    ${`${r.stdout}${r.stderr}`.trim().split('\n').slice(-5).join('\n    ')}`);
        return true;
      }
    }
    const changed = [];
    const orphans = [];
    for (const rel of sourceFiles(copy)) {
      const regenerated = readFileSync(join(copy, rel), 'utf8');
      if (!G_HEADER.test(regenerated.replace(/\r\n/g, '\n'))) continue;
      if (regenerated.includes(ORPHAN_MARK)) {
        orphans.push(`? ${rel}`);
        continue;
      }
      const original = join(host, rel);
      if (!existsSync(original)) changed.push(`+ ${rel}`);
      else if (body(readFileSync(original, 'utf8')) !== body(regenerated)) changed.push(`~ ${rel}`);
    }
    const label = `${basename(host)} generate`;
    if (!changed.length && !orphans.length) {
      console.log(`[ok] ${label}: ${marked.length} G dosyası Generator çıktısıyla aynı, sahipsiz yok`);
      return false;
    }
    const lines = [...changed, ...orphans].map((c) => c.replace(/\\/g, '/'));
    console.log(`[FARK] ${label}: ${changed.length} G dosyası farklı, ${orphans.length} sahipsiz (Generator artık üretmiyor)\n    ${lines.join('\n    ')}`);
    return true;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

let failed = false;
for (const host of hosts) {
  if (checkAssets(host)) failed = true;
  if (generated && checkGenerated(host)) failed = true;
}
process.exitCode = failed ? 1 : 0;
