#!/usr/bin/env node
// Ortak .cursor/rules dosyalarını Generator'dan host'lara yazar; işaretin altındaki "Bu projeye özel" bölümüne dokunmaz.
import { existsSync, lstatSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/generator-assets/cursor-rules');
const MARKER = '<!-- rules-sync: bu satırın altı projeye aittir -->';
const HOME = process.env.HOME ?? '';
const DEFAULT_HOSTS = ['Projects/AtaAllWorkspace/SharedFrame', 'Projects/AtaAllWorkspace/AlphaTerminal', 'Projects/AtaAllWorkspace/Varlik360', 'Projects/AtaAllWorkspace/CeyizDefterim'].map((p) => join(HOME, p));
// Generator'ın kendi .cursor/rules klasöründe yalnız bu kopyalar durur.
const SELF_FILES = ['AtaProjectCommon.mdc', 'frontend.admin.mdc'];

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
const unknown = [...flags].filter((f) => !['--apply', '--force'].includes(f));
if (unknown.length) {
  console.error('Kullanım: node scripts/rules-sync.mjs [host…] [--apply] [--force]\n  host yoksa 4 proje + Generator. --apply yazar; --force işareti olmayan dosyanın üstüne yazar (eski içerik gider).');
  process.exit(1);
}
const apply = flags.has('--apply');
const force = flags.has('--force');
const hosts = args.filter((a) => !a.startsWith('--')).map((a) => resolve(a));

const pad = (n) => String(n).padStart(2, '0');
const now = new Date();
const stamp = `${pad(now.getDate())}.${pad(now.getMonth() + 1)}.${now.getFullYear()} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`;
const HEADER_RE = /^<!-- Auto Generated By Generator - .* -->\n/m;

// Frontmatter'dan hemen sonra Generator damgası; karşılaştırma damgasız yapılır.
const withHeader = (text) => text.replace(/^(---\n[\s\S]*?\n---\n)/, `$1<!-- Auto Generated By Generator - ${stamp} -->\n`);
const withoutHeader = (text) => text.replace(HEADER_RE, '');

const splitAtMarker = (text) => {
  const i = text.indexOf(MARKER);
  return i < 0 ? null : { head: text.slice(0, i + MARKER.length), tail: text.slice(i + MARKER.length) };
};

const sourceFiles = readdirSync(source).filter((f) => f.endsWith('.mdc'));
const heads = Object.fromEntries(
  sourceFiles.map((f) => {
    const parts = splitAtMarker(readFileSync(join(source, f), 'utf8'));
    if (!parts) throw new Error(`Kaynakta işaret yok: ${f}`);
    return [f, parts.head];
  })
);

const filesFor = (host) => {
  if (resolve(host) === resolve(root)) return SELF_FILES;
  const list = ['AtaProjectCommon.mdc', 'general.mdc', 'backend.mdc'];
  if (['admin', 'web', 'mobile'].some((app) => existsSync(join(host, 'apps', app)))) list.push('frontend.common.mdc');
  if (existsSync(join(host, 'apps/admin'))) list.push('frontend.admin.mdc');
  if (existsSync(join(host, 'apps/web'))) list.push('frontend.web.mdc');
  if (existsSync(join(host, 'apps/mobile'))) list.push('frontend.mobile.mdc');
  return list;
};

let pending = 0;
for (const host of hosts.length ? hosts : [...DEFAULT_HOSTS, root]) {
  const dir = join(host, '.cursor/rules');
  console.log(`\n${host}`);
  const wanted = filesFor(host);
  for (const file of wanted) {
    const target = join(dir, file);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    const parts = current ? splitAtMarker(current) : null;
    if (current && !parts && !force) {
      console.log(`  işaret yok   ${file} (atlandı; projeye özel kısmı işaretin altına taşıyın ya da --force)`);
      continue;
    }
    const tail = parts ? parts.tail : '\n';
    const next = heads[file] + tail;
    if (current && withoutHeader(current) === withoutHeader(next) && !lstatSync(target).isSymbolicLink()) {
      console.log(`  aynı         ${file}`);
      continue;
    }
    pending++;
    const isLink = current !== null && lstatSync(target).isSymbolicLink();
    console.log(`  ${current ? 'farklı' : 'eksik '}       ${file}${isLink ? ' (symlink → dosya)' : ''}`);
    if (!apply) continue;
    // Symlink'in hedefine yazmak başka projenin notunu ezer; bağ kaldırılıp yerine dosya yazılır.
    if (isLink) unlinkSync(target);
    writeFileSync(target, withHeader(withoutHeader(next)));
  }
  if (existsSync(dir)) {
    for (const extra of readdirSync(dir).filter((f) => f.endsWith('.mdc') && !wanted.includes(f) && resolve(host) !== resolve(root))) {
      console.log(`  ortak değil  ${extra}`);
    }
  }
}
console.log(apply ? `\n${pending} dosya yazıldı.` : `\n${pending} dosya farklı/eksik. Yazmak için --apply.`);
