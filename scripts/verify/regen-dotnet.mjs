{
  const varlikAdmin = '/Users/atakanatabey/Projects/VarlikALL/Varlik360/apps/admin';
  const fe = join(varlikAdmin, '.gen-dotnet-admin-check');
  rmSync(fe, { recursive: true, force: true });
  const flowModels = gen.loadDotnetModels(gen.findDotnetHost(out)).map(m => m.model);
  const results = flowModels.map(model => gen.generateAdminConfig({ model, frontendRoot: fe, backendRoot: out, baseUrl: '/api' }));
  check('admin config: generated for every module', results.every(r => r.success), results.map(r => r.error).filter(Boolean));
  check('admin config: endpoints read from .NET (no fallback warning)', results.every(r => !(r.warnings ?? []).length), results.flatMap(r => r.warnings ?? []));
  const cfg = name => gen.toAdminResourceConfig({ model: flowModels.find(m => m.entityName === name), endpoint: '' }).config;
  const tpl = cfg('Templates');
  check('admin config: relation ref (templates.eventTypeId → event-types)',
    tpl.fields.find(f => f.name === 'eventTypeId')?.kind === 'relation' && tpl.fields.find(f => f.name === 'eventTypeId')?.ref === 'event-types');
  check('admin config: no id field', !tpl.fields.some(f => f.name === 'id' || f.name === '_id'));
  check('admin config: decimal / object / map', cfg('MembershipPlans').fields.some(f => f.name === 'limits' && f.kind === 'object'));
  writeFileSync(join(fe, 'tsconfig.json'), JSON.stringify({
    extends: '../tsconfig.app.json',
    compilerOptions: { noEmit: true, baseUrl: '.', paths: { axios: ['../../../node_modules/axios'] }, tsBuildInfoFile: null, incremental: false },
    include: ['src/**/*.ts']
  }, null, 2));
  const tsc = spawnSync('npx', ['tsc', '--noEmit', '-p', join(fe, 'tsconfig.json')], { cwd: varlikAdmin, encoding: 'utf8' });
  const tsErrors = `${tsc.stdout}${tsc.stderr}`.split('\n').filter(l => l.includes('error TS'));
  check('admin config: tsc against admin-base types', tsErrors.length === 0, tsErrors.slice(0, 5).join('\n'));
  rmSync(fe, { recursive: true, force: true });
}

