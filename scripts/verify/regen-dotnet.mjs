// Parser round trip (D5): the entity file gives back the file-owned parts of the model.
function expectedField(f, names) {
  const objectFields = f.kind === 'object' && f.object?.fields?.length ? f.object.fields : null;
  const kind = f.kind === 'object' && !objectFields ? 'json' : f.kind;
  const target = f.kind === 'reference' && f.reference?.target && names.has(f.reference.target) ? f.reference.target : undefined;
  const scalarDefault = ['string', 'number', 'decimal', 'boolean', 'enum'].includes(f.kind) && !f.isArray ? f.default : undefined;
  return {
    name: f.name, kind, isArray: !!f.isArray, required: f.required === true && f.nullable !== true,
    unique: !!f.unique, trim: !!f.trim, enum: f.kind === 'enum' ? f.enum?.values : undefined,
    default: scalarDefault ?? undefined, target,
    subs: objectFields ? objectFields.map(x => `${x.name}:${x.kind === 'enum' ? 'string' : x.kind}:${x.required && x.nullable !== true}`) : undefined
  };
}
function parsedField(f) {
  return {
    name: f.name, kind: f.kind, isArray: !!f.isArray, required: !!f.required, unique: !!f.unique, trim: !!f.trim,
    enum: f.enum?.values, default: f.default ?? undefined, target: f.reference?.target,
    subs: f.object?.fields ? f.object.fields.map(x => `${x.name}:${x.kind}:${x.required}`) : undefined
  };
}
function roundTrip(label, list) {
  const host = gen.findDotnetHost(out);
  const folders = new Map(gen.listDotnetEntityFiles(host).map(f => [f.fileName.replace(/\.cs$/, ''), f.folder]));
  const names = new Set(list.map(m => m.entityName));
  const diffs = [];
  for (const model of list) {
    const { entity, folder } = gen.dotnetModuleNames(model.entityName);
    const parsed = gen.parseDotnetEntity(join(out, 'src', `${app}.Domain`, folder, `${entity}.cs`), folders);
    if (parsed.entityName !== folder) diffs.push(`${model.entityName}: entityName ${parsed.entityName}`);
    for (const f of model.fields.filter(x => !['_id', 'id', 'createdAt', 'updatedAt'].includes(x.name))) {
      const want = JSON.stringify(expectedField(f, names));
      const p = parsed.fields.find(x => x.name === f.name);
      const got = p ? JSON.stringify(parsedField(p)) : 'missing';
      if (want !== got) diffs.push(`${model.entityName}.${f.name}\n        want ${want}\n        got  ${got}`);
    }
  }
  check(`${label}: parser round trip`, diffs.length === 0, diffs.length ? `\n      ${diffs.join('\n      ')}` : `${list.length} models`);
}
roundTrip('models', models);

