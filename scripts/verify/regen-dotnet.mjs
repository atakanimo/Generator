// 4. App flow (D5): the IPC functions the app calls — bootstrap, scan, model editor, generate, admin endpoint lookup.
reset(join(outBase, 'app-flow'));
const flowApp = 'FlowHost';
check('flow: bootstrap refuses a pair dotnet-ef does not generate for', !gen.bootstrapDotnetProject(out, flowApp, { database: 'postgres', idType: 'objectid' }).success);
const boot = gen.bootstrapDotnetProject(out, flowApp, db);
const flowWorkspace = gen.readWorkspaceManifest(out)?.workspace;
check('flow: bootstrap', boot.success && flowWorkspace?.backendStack === 'dotnet-ef', boot.error);
check('flow: manifest records database + id type', flowWorkspace?.database === db.database && flowWorkspace?.idType === db.idType, flowWorkspace);
let scan = await gen.scanProject(out);
check('flow: scan detects dotnet-ef (empty host)', scan.success && scan.detectedType === 'dotnet-ef' && scan.models.length === 0, scan);
const byName = Object.fromEntries(models.map(m => [m.entityName, m]));
for (const name of ['EventTypes', 'Documents', 'MembershipPlans', 'Templates']) {
  const draft = { model: { ...byName[name], fields: byName[name].fields.filter(f => f.name !== 'createdAt' && f.name !== 'updatedAt') } };
  const r = gen.writeDotnetModel(out, draft);
  check(`flow: model editor create ${name}`, r.success, r.error);
}
scan = await gen.scanProject(out);
check('flow: scan lists entity files', scan.models.length === 4, scan.models.map(m => m.fileName));
const loaded = Object.fromEntries(gen.loadDotnetModels(gen.findDotnetHost(out)).map(m => [m.model.entityName, m.model]));
check('flow: manifest settings survive (api, filter)', loaded.EventTypes?.api?.requiresAuth === false
  && loaded.Templates?.fields.find(f => f.name === 'eventTypeId')?.reference?.populate?.join() === '_id,name,isActive', loaded.EventTypes?.api);
const draftBack = gen.loadDotnetModelDraft(join(out, 'src', `${flowApp}.Domain`, 'Documents', 'Document.cs'));
check('flow: load model draft', draftBack.success && draftBack.draft.model.fields.some(f => f.name === 'status' && f.enum?.values?.length === 3), draftBack.error);
// Saved through the model editor, then regenerated from file + manifest (mergeModel): same code for every model.
const drift = Object.values(loaded).flatMap(m => gen.generateDotnetBackend(out, m).writtenFiles ?? ['error']);
check('flow: editor model = merged model (no file changes)', drift.length === 0, drift.join(', '));
const same = gen.generateDotnetBackend(out, loaded.Templates);
check('flow: generate unchanged model writes nothing', same.success && same.writtenFiles.length === 0, same.writtenFiles ?? same.error);
check('flow: generate notes the schema step', same.notes?.some(n => db.database === 'mongodb'
  ? n.includes('EnsureIndexesOnStartup')
  : n.includes(`dotnet ef migrations add`) && n.includes(`${flowApp}.Infrastructure`)), same.notes);
const edited = { ...loaded.EventTypes, fields: [...loaded.EventTypes.fields, { name: 'color', kind: 'string', isArray: false, required: false, filter: { searchable: true, type: 'regex' } }] };
const changed = gen.generateDotnetBackend(out, edited);
check('flow: generate edited model', changed.success && changed.writtenFiles.some(f => f.endsWith('EventType.cs')), changed.writtenFiles ?? changed.error);
const docs = gen.generateDotnetBackend(out, loaded.Documents);
check('flow: contract-closed operations reported', docs.notes?.some(n => n.includes('create, update, delete')), docs.notes);
check('flow: admin endpoint from AdminEndpoints.cs', gen.findAdminMountPath(out, 'event-types') === '/api/event-types/admin');
const related = await gen.getRelatedModelFieldNames(out, 'EventTypes', 'dotnet-ef');
check('flow: related model fields', related.success && related.fields.some(f => f.name === 'name' && f.regexSearchable), related.error);
const parsedEntity = gen.parseNormalizedModel(join(out, 'src', `${flowApp}.Domain`, 'Templates', 'Template.cs'), 'dotnet-ef');
check('flow: parseModel (.cs)', parsedEntity.success && parsedEntity.model.fields.find(f => f.name === 'eventTypeId')?.reference?.target === 'EventTypes', parsedEntity.error);
buildAndTest('flow');

