/**
 * .NET EF Core generator gate (plan backend-dotnet-efcore §8).
 *
 * Into `scripts/verify/out/dotnet/<label>/` (gitignored):
 *  - `empty/`: bootstrap only (D1) → `dotnet build` (0 errors, 0 warnings) + `dotnet test` → bootstrap again writes nothing.
 *  - `models/`: `fixtures/dotnet/models.json` generated (D2–D3) → build + test → generate again writes nothing.
 *  - `golden/`: the Varlik360 golden set (`fixtures/varlik360.manifest.v3.json`) generated (D3) → build + idempotent.
 *  - `python-parity/`: `fixtures/python/subscription-plans.models.json` (the .NET side of the Python parity suite).
 *  - parser round trip (D5): entity files of `models/`, `golden/` and `python-parity/` read back = the file-owned parts.
 *  - `app-flow/`: the app's IPC functions (D5): bootstrap, scan, model editor, generate, admin endpoint, related fields.
 *  - admin FE config from the `app-flow/` host → tsc against @atakanimo/ata-admin-base (temp folder in Varlik360 apps/admin).
 *
 * Run:  node scripts/verify/regen-dotnet.mjs [label] [--db postgres|sqlserver|mongodb] [--id uuid-v7|objectid]
 *       (default label: reference, db: postgres, id: uuid-v7)
 */
import { build } from 'esbuild';
import { spawnSync } from 'child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { dirname, join, relative } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const option = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const optionValues = new Set(['--db', '--id'].filter((n) => args.includes(n)).map((n) => args.indexOf(n) + 1));
const label = args.find((a, i) => !a.startsWith('--') && !optionValues.has(i)) ?? 'reference';
const app = 'SampleHost';
const db = { database: option('--db', 'postgres'), idType: option('--id', 'uuid-v7') };
const outBase = join(root, 'scripts/verify/out/dotnet', label);
let out = outBase;

async function loadBundle() {
  const outfile = join(root, 'scripts/verify/out/.harness/dotnet-bundle.mjs');
  mkdirSync(dirname(outfile), { recursive: true });
  await build({
    entryPoints: [join(root, 'scripts/verify/_dotnet-entry.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile,
    plugins: [
      {
        name: 'stub-electron',
        setup(api) {
          api.onResolve({ filter: /^electron$/ }, () => ({ path: 'electron', namespace: 'stub-electron' }));
          api.onLoad({ filter: /.*/, namespace: 'stub-electron' }, () => ({
            contents: 'export const app = { getAppPath: () => process.cwd(), isPackaged: false };',
            loader: 'js'
          }));
        }
      }
    ],
    logLevel: 'silent'
  });
  return import(pathToFileURL(outfile).href);
}

function run(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: out, encoding: 'utf8', env: { ...process.env, DOTNET_CLI_UI_LANGUAGE: 'en' } });
  return { ok: r.status === 0, output: `${r.stdout}${r.stderr}` };
}

let failed = 0;
function check(name, ok, detail = '') {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? `  ${detail}` : ''}`);
  if (!ok) failed++;
}

const gen = await loadBundle();
const header = '// <auto-generated by Generator />\n#nullable enable\n';
const models = JSON.parse(readFileSync(join(root, 'scripts/verify/fixtures/dotnet/models.json'), 'utf8'));

function buildAndTest(name) {
  const b = run('dotnet', ['build', '-nologo', '-clp:Summary']);
  const warnings = /(\d+) Warning\(s\)/.exec(b.output)?.[1];
  const errors = /(\d+) Error\(s\)/.exec(b.output)?.[1];
  check(`${name}: dotnet build`, b.ok && warnings === '0' && errors === '0', `warnings=${warnings} errors=${errors}`);
  if (!b.ok) console.log([...new Set(b.output.split('\n').filter(l => /error|warning/i.test(l)))].slice(0, 40).join('\n'));
  const t = run('dotnet', ['test', '--no-build', '-nologo', '-v', 'q']);
  check(`${name}: dotnet test`, t.ok, t.ok ? '' : t.output.slice(-1500));
}

function reset(dir) {
  out = dir;
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
}

