/**
 * .NET EF Core host on disk (plan backend-dotnet-efcore §3, §7): solution name = app name, Domain entity files.
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'fs';
import { join } from 'path';

export interface DotnetHost {
  root: string;
  app: string;
  solutionFile: string;
  /** Npgsql / EF Core packages found (Directory.Packages.props or a project file). */
  efCorePostgres: boolean;
}

export interface DotnetEntityFile {
  path: string;
  fileName: string;
  /** Module folder (`EventTypes`), also the model's `entityName`. */
  folder: string;
  /** Starts with the Generator header; hand-written entities are only relation targets. */
  generated: boolean;
}

const GENERATED_HEADER = '// <auto-generated by Generator />';

function readIfExists(path: string): string {
  try {
    return existsSync(path) ? readFileSync(path, 'utf8') : '';
  } catch {
    return '';
  }
}

/** `<App>.slnx` / `<App>.sln` in the root with `src/<App>.Domain` next to it; null otherwise. */
export function findDotnetHost(root: string): DotnetHost | null {
  let entries: string[];
  try {
    entries = readdirSync(root);
  } catch {
    return null;
  }
  const solutionFile = entries.find((n) => n.endsWith('.slnx')) ?? entries.find((n) => n.endsWith('.sln'));
  if (!solutionFile) return null;
  const app = solutionFile.replace(/\.slnx?$/, '');
  if (!existsSync(join(root, 'src', `${app}.Domain`))) return null;
  const packages = [
    readIfExists(join(root, 'Directory.Packages.props')),
    readIfExists(join(root, 'src', `${app}.Infrastructure`, `${app}.Infrastructure.csproj`))
  ].join('\n');
  return { root, app, solutionFile, efCorePostgres: /Npgsql\.EntityFrameworkCore\.PostgreSQL/.test(packages) };
}

/** `src/<App>.Domain/<Folder>/<Entity>.cs` (not `*.Custom.cs`, not `Common/`). */
export function listDotnetEntityFiles(host: DotnetHost): DotnetEntityFile[] {
  const domain = join(host.root, 'src', `${host.app}.Domain`);
  const out: DotnetEntityFile[] = [];
  for (const folder of readdirSync(domain).sort()) {
    const dir = join(domain, folder);
    if (folder === 'Common' || folder === 'bin' || folder === 'obj' || !statSync(dir).isDirectory()) continue;
    for (const fileName of readdirSync(dir).sort()) {
      if (!fileName.endsWith('.cs') || fileName.endsWith('.Custom.cs')) continue;
      const path = join(dir, fileName);
      const content = readIfExists(path);
      if (!/\bclass\s+\w+\s*:\s*AuditableEntity\b/.test(content)) continue;
      out.push({ path, fileName, folder, generated: content.startsWith(GENERATED_HEADER) });
    }
  }
  return out;
}
