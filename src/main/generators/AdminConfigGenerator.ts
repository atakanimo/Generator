/**
 * Admin FE output (plan 6 §2): per module, in a folder named like the admin route (`modules/symbol-types/`):
 * `<module>.generated.config.ts` (data, rewritten every run) + `<module>.generated.ts` (`extendResource`, created
 * once and never overwritten — actions / custom cells go here), and `modules/resources.generated.ts`
 * (every module that has a config). Pages, routes and the menu come from `@atakanimo/ata-admin-base`.
 */
import { existsSync, readdirSync, readFileSync } from 'fs';
import { findAdminMountPath } from '../utils/backendAppFile.js';
import { dirname, join, resolve } from 'path';
import { resolveAdminOperations, type NormalizedModel } from '../../shared/normalizedModel.js';
import { safeWriteFile } from '../utils/fileUtils.js';
import { log } from '../utils/logger.js';
import { moduleNameFromEntity } from '../utils/namingUtils.js';
import { toAdminResourceConfig, type AdminFieldConfig, type AdminResourceConfig, type SkippedField } from './adminResourceConfig.js';

export interface AdminConfigGenerateOptions {
  model: NormalizedModel;
  /** Admin FE project root (contains `src/modules`). */
  frontendRoot: string;
  /** Backend project root: the admin router mount path is read from its app file. */
  backendRoot?: string;
  /** Fallback base when the mount is not found, e.g. `/api`. */
  baseUrl?: string;
  features?: { updatable?: boolean; deletable?: boolean };
}

export interface AdminConfigGenerateResult {
  success: boolean;
  files?: { config: string; extension?: string; registry: string };
  skipped?: SkippedField[];
  warnings?: string[];
  error?: string;
}

const HEADER = '// Auto Generated By Generator';

function camelModuleName(entityName: string): string {
  return entityName.charAt(0).toLowerCase() + entityName.slice(1);
}

function formatDate(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(date.getDate())}.${pad(date.getMonth() + 1)}.${date.getFullYear()} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
}

// --- Rendering -----------------------------------------------------------------------------------------

function literal(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;
  if (value !== null && typeof value === 'object') {
    return `{ ${Object.entries(value).map(([k, v]) => `${k}: ${literal(v)}`).join(', ')} }`;
  }
  return String(value);
}

const FIELD_KEY_ORDER: Array<keyof AdminFieldConfig> = [
  'name',
  'kind',
  'label',
  'options',
  'numbers',
  'ref',
  'display',
  'populate',
  'valueKind',
  'typeName',
  'isArray',
  'required',
  'nullable',
  'readonly',
  'hideOnCreate',
  'hideOnUpdate',
  'writeOnly',
  'list',
  'sortable',
  'filter',
  'default',
  'component',
  'format',
  'numberFormat',
  'dateFormat',
  'constraints'
];

function renderField(field: AdminFieldConfig, indent: string): string {
  const parts = FIELD_KEY_ORDER.filter(key => field[key] !== undefined).map(key => `${key}: ${literal(field[key])}`);
  if (!field.fields) return `${indent}{ ${parts.join(', ')} }`;
  const inner = field.fields.map(sub => renderField(sub, `${indent}    `)).join(',\n');
  return `${indent}{\n${indent}  ${parts.join(', ')},\n${indent}  fields: [\n${inner}\n${indent}  ]\n${indent}}`;
}

export function renderAdminConfigFile(config: AdminResourceConfig, exportName: string, skipped: SkippedField[], date: Date): string {
  const lines = [
    `${HEADER} - ${formatDate(date)}`,
    `// Admin resource config (@atakanimo/ata-admin-base). Do not edit: change the model in the Generator and regenerate;`,
    `// behaviour (actions, custom cells, icon) goes in the sibling extension file.`,
    `import { defineResourceSchema } from '@atakanimo/ata-admin-base';`,
    ``
  ];
  for (const s of skipped) lines.push(`// Not in the admin: \`${s.name}\` — ${s.reason}`);
  if (skipped.length) lines.push('');
  lines.push(`export const ${exportName} = defineResourceSchema({`);
  lines.push(`  schemaVersion: ${config.schemaVersion},`);
  lines.push(`  name: ${literal(config.name)},`);
  lines.push(`  endpoint: ${literal(config.endpoint)},`);
  if (config.label) lines.push(`  label: ${literal(config.label)},`);
  if (config.titleField) lines.push(`  titleField: ${literal(config.titleField)},`);
  if (config.operations) lines.push(`  operations: ${literal(config.operations)},`);
  lines.push(`  fields: [`);
  lines.push(config.fields.map(f => renderField(f, '    ')).join(',\n'));
  lines.push(`  ]`);
  lines.push(`});`);
  return `${lines.join('\n')}\n`;
}

/** `detail`: the model's admin API has getOne (or `detailOnly` fields), so rows get the read-only detail drawer. */
function renderExtensionFile(camel: string, moduleName: string, detail: boolean): string {
  return [
    `// Admin behaviour for \`${moduleName}\`: actions, custom cells, icon (@atakanimo/ata-admin-base \`extendResource\`).`,
    `// Created once by the Generator, never overwritten: edit freely.`,
    `import { extendResource } from '@atakanimo/ata-admin-base';`,
    `import { ${camel}Schema } from './${moduleName}.generated.config';`,
    ``,
    `export const ${camel}Resource = extendResource(${camel}Schema, {${detail ? ' detail: true ' : ''}});`,
    ``
  ].join('\n');
}

/** Every `modules/<module>/<module>.generated.ts` exporting a `…Resource`, in folder order. */
function collectResources(modulesDir: string): Array<{ module: string; exportName: string }> {
  if (!existsSync(modulesDir)) return [];
  const out: Array<{ module: string; exportName: string }> = [];
  for (const module of readdirSync(modulesDir).sort()) {
    const file = join(modulesDir, module, `${module}.generated.ts`);
    if (!existsSync(file)) continue;
    const match = /export\s+const\s+(\w+Resource)\b/.exec(readFileSync(file, 'utf-8'));
    if (match) out.push({ module, exportName: match[1] });
  }
  return out;
}

export function renderRegistryFile(entries: Array<{ module: string; exportName: string }>, date: Date): string {
  return [
    `${HEADER} - ${formatDate(date)}`,
    `// Every @atakanimo/ata-admin-base resource of the admin panel (routes + menu come from \`createAdminRoutes(resources)\`).`,
    `import type { AnyResource } from '@atakanimo/ata-admin-base';`,
    ...entries.map(e => `import { ${e.exportName} } from './${e.module}/${e.module}.generated';`),
    ``,
    `export const resources: readonly AnyResource[] = [${entries.length ? `\n${entries.map(e => `  ${e.exportName}`).join(',\n')}\n` : ''}];`,
    ``
  ].join('\n');
}

// --- Generate ------------------------------------------------------------------------------------------

function hasDetailView(model: NormalizedModel): boolean {
  return resolveAdminOperations(model.api).includes('getOne') || model.fields.some(f => f.access?.detailOnly === true);
}

/** `extensions.detail` exists from admin-base 0.1.6; an older host package (or none installed) gets no `detail`.
 * The package is looked up like Node does: the FE root's `node_modules`, then each parent's (hoisted workspaces). */
function hostSupportsDetail(frontendRoot: string): boolean {
  let dir = resolve(frontendRoot);
  let pkg = '';
  for (;;) {
    const candidate = join(dir, 'node_modules', '@atakanimo', 'ata-admin-base', 'package.json');
    if (existsSync(candidate)) {
      pkg = candidate;
      break;
    }
    const parent = dirname(dir);
    if (parent === dir) return false;
    dir = parent;
  }
  const [major = 0, minor = 0, patch = 0] = String(JSON.parse(readFileSync(pkg, 'utf-8')).version ?? '')
    .split('.')
    .map(n => Number.parseInt(n, 10) || 0);
  return major > 0 || minor > 1 || (minor === 1 && patch >= 6);
}

export function generateAdminConfig(options: AdminConfigGenerateOptions): AdminConfigGenerateResult {
  try {
    const { model, frontendRoot, backendRoot, baseUrl, features } = options;
    const moduleName = moduleNameFromEntity(model.entityName);
    const camel = camelModuleName(model.entityName);
    const warnings: string[] = [];

    let endpoint = backendRoot ? findAdminMountPath(backendRoot, moduleName) : null;
    if (!endpoint) {
      endpoint = `${(baseUrl || '/api').replace(/\/+$/, '')}/${moduleName}/admin`;
      warnings.push(`Admin route of '${moduleName}' not found in the backend app file; using ${endpoint}`);
    }

    const { config, skipped } = toAdminResourceConfig({ model, endpoint, features });
    const now = new Date();
    const modulesDir = join(frontendRoot, 'src', 'modules');
    // Folder = admin route segment = resource name (`symbol-types`).
    const moduleDir = join(modulesDir, config.name);

    const configFile = join(moduleDir, `${config.name}.generated.config.ts`);
    const written = safeWriteFile(configFile, renderAdminConfigFile(config, `${camel}Schema`, skipped, now), { ensureDirectory: true, createBackup: false });
    if (!written.success) return { success: false, error: written.error };

    const extensionFile = join(moduleDir, `${config.name}.generated.ts`);
    let extension: string | undefined;
    if (!existsSync(extensionFile)) {
      const ext = safeWriteFile(extensionFile, renderExtensionFile(camel, config.name, hasDetailView(model) && hostSupportsDetail(frontendRoot)), { ensureDirectory: true, createBackup: false });
      if (!ext.success) return { success: false, error: ext.error };
      extension = extensionFile;
    }

    const registryFile = join(modulesDir, 'resources.generated.ts');
    const reg = safeWriteFile(registryFile, renderRegistryFile(collectResources(modulesDir), now), { ensureDirectory: true, createBackup: false });
    if (!reg.success) return { success: false, error: reg.error };

    for (const w of warnings) log(w, 'warn');
    for (const s of skipped) log(`Admin config: field '${s.name}' skipped (${s.reason})`, 'warn');
    log(`Admin config generated | ${JSON.stringify({ entity: model.entityName, configFile, extension })}`, 'info');
    return { success: true, files: { config: configFile, extension, registry: registryFile }, skipped, warnings };
  } catch (error) {
    return { success: false, error: error instanceof Error ? error.message : 'Unknown error' };
  }
}
