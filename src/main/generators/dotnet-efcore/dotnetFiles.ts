/**
 * File writing for the .NET EF Core generator: G (header-owned, rewritten), K / asset (created once, never overwritten).
 */
import Handlebars from 'handlebars';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { dirname, join, relative } from 'path';
import { getGeneratorRoot, getTemplatesDir } from '../../utils/templateHelpers.js';
import { APP_TOKEN, APP_TOKEN_LOWER } from './dotnetLayout.js';

/** Roslyn treats files starting with this comment as generated (hence `#nullable enable` on line 2). */
export const DOTNET_GENERATED_HEADER = '// <auto-generated by Generator />';

export type WriteAction = 'created' | 'updated' | 'unchanged' | 'skipped-user-owned' | 'skipped-exists';
export interface WrittenFile { path: string; action: WriteAction }

export function dotnetAssetsDir(): string {
  return join(getGeneratorRoot(), 'src', 'generator-assets', 'dotnet-efcore');
}


const templateCache = new Map<string, HandlebarsTemplateDelegate>();

export function renderDotnetTemplate(name: string, data: unknown): string {
  let template = templateCache.get(name);
  if (!template) {
    template = Handlebars.compile(readFileSync(join(getTemplatesDir('backend-dotnet-efcore'), `${name}.hbs`), 'utf8'), { noEscape: true });
    templateCache.set(name, template);
  }
  return template(data);
}

export function applyAppTokens(text: string, app: string): string {
  return text.split(APP_TOKEN).join(app).split(APP_TOKEN_LOWER).join(app.toLowerCase());
}

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

/** G file: rewritten when content changes; a file without the header is user-owned and left alone. */
export function writeGenerated(path: string, content: string): WrittenFile {
  if (!content.startsWith(DOTNET_GENERATED_HEADER)) {
    throw new Error(`Generated .NET file must start with the Generator header: ${path}`);
  }
  if (existsSync(path)) {
    const current = readFileSync(path, 'utf8');
    if (!current.startsWith(DOTNET_GENERATED_HEADER)) return { path, action: 'skipped-user-owned' };
    if (current === content) return { path, action: 'unchanged' };
    write(path, content);
    return { path, action: 'updated' };
  }
  write(path, content);
  return { path, action: 'created' };
}

/** K file / asset: created when missing, never overwritten. */
export function writeOnce(path: string, content: string): WrittenFile {
  if (existsSync(path)) return { path, action: 'skipped-exists' };
  write(path, content);
  return { path, action: 'created' };
}

export function listFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    if (name === '.DS_Store') continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full));
    else out.push(full);
  }
  return out.sort();
}

/** Copies a token-bearing asset tree (paths and contents) into `targetDir`, create-only. */
export function copyAssetTree(sourceDir: string, targetDir: string, app: string): WrittenFile[] {
  return listFiles(sourceDir).map((file) =>
    writeOnce(join(targetDir, applyAppTokens(relative(sourceDir, file), app)), applyAppTokens(readFileSync(file, 'utf8'), app))
  );
}
