/**
 * Shared auth layer for a new .NET host (docs/backend/auth.md). Runs right after the skeleton (`bootstrapDotnetHost`):
 *
 * - `src/generator-assets/dotnet-efcore/auth/<Layer>/**` → `src/<App>.<Layer>/`, with the provider layer on top
 *   (`auth/providers/relational` for PostgreSQL / SQL Server, `auth/providers/mongodb`). Create-only (K); module
 *   conditions (`// @auth-file`, `// @if`) keep only the picked modules (`applyAuthBlocks`).
 * - `auth/_skeleton/**` → host root, replacing the skeleton files the host bootstrap has just written (`Program.cs`
 *   wires the auth module, the seed and the rate limiter).
 * - `Infrastructure/Auth/InitialAdmin.cs`: first admin (bcrypt hash only).
 * - `Directory.Packages.props` + Infrastructure csproj: `BCrypt.Net-Next`. `.env.example`: TTLs, rate limit, module keys.
 *
 * The `Users` model is a normal manifest model, generated by the caller (`bootstrapDotnetProject`).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join, relative } from 'path';
import type { HostDatabase } from '../../../shared/backendDatabase.js';
import { authUsesMail, type AuthModule } from '../../../shared/authModules.js';
import { applyAuthBlocks } from '../../utils/authBlocks.js';
import type { AuthSeedAdmin } from '../../utils/authSeed.js';
import { DOTNET_LAYERS, dotnetLayout } from './dotnetLayout.js';
import { WrittenFile, applyAppTokens, dotnetAssetsDir, listFiles, writeOnce } from './dotnetFiles.js';

export const DOTNET_BCRYPT_PACKAGE = { name: 'BCrypt.Net-Next', version: '4.0.3' } as const;

/** .NET env names of the module keys (`__` = configuration section). */
const DOTNET_MODULE_ENV: Partial<Record<AuthModule, string[]>> = {
  google: ['Auth__GoogleClientIds='],
  // Team / key / .p8: Apple token'ı hesap silinince iptal etmek için (boşsa iptal atlanır).
  apple: ['Auth__AppleClientIds=', 'Auth__AppleTeamId=', 'Auth__AppleKeyId=', 'Auth__ApplePrivateKey=']
};
const DOTNET_MAIL_ENV = ['Smtp__Host=', 'Smtp__Port=587', 'Smtp__User=', 'Smtp__Password=', 'Mail__From='];

const authDir = () => join(dotnetAssetsDir(), 'auth');

/** Files of the trees by relative path; a later tree replaces an earlier one. */
function collect(dirs: string[]): Map<string, string> {
  const files = new Map<string, string>();
  for (const dir of dirs) {
    if (!existsSync(dir)) continue;
    for (const file of listFiles(dir)) files.set(relative(dir, file).replace(/\\/g, '/'), file);
  }
  return files;
}

function render(file: string, app: string, modules: readonly AuthModule[]): string | null {
  const content = applyAuthBlocks(readFileSync(file, 'utf8'), modules);
  return content === null ? null : applyAppTokens(content, app);
}

const csString = (value: string) => JSON.stringify(value);

function initialAdminFile(app: string, admin: AuthSeedAdmin): string {
  return [
    `namespace ${app}.Infrastructure.Auth;`,
    '',
    '/// <summary>',
    '/// İlk admin (docs/backend/auth.md "İlk admin"): Generator yazdı, yalnız bcrypt hash\'ini tutar. Açılışta hiç',
    '/// <c>admin</c> yoksa bu kayıt oluşturulur; sonra bir daha okunmaz.',
    '/// </summary>',
    'public static class InitialAdmin',
    '{',
    `    public const string Email = ${csString(admin.email)};`,
    `    public const string Name = ${csString(admin.name)};`,
    `    public const string PasswordHash = ${csString(admin.passwordHash)};`,
    '}',
    ''
  ].join('\n');
}

/** `<PackageVersion>` in the central props and `<PackageReference>` in the Infrastructure project (once). */
function addBcryptPackage(root: string, app: string): void {
  const { name, version } = DOTNET_BCRYPT_PACKAGE;
  const props = join(root, 'Directory.Packages.props');
  const xml = readFileSync(props, 'utf8');
  if (!xml.includes(`Include="${name}"`)) {
    const at = /^([ \t]*)<PackageVersion /m.exec(xml);
    if (!at) throw new Error(`${props}: <PackageVersion> yok; ${name} eklenemedi.`);
    writeFileSync(props, `${xml.slice(0, at.index)}${at[1]}<PackageVersion Include="${name}" Version="${version}" />\n${xml.slice(at.index)}`);
  }
  const csproj = join(dotnetLayout(root, app).projectDir('Infrastructure'), `${app}.Infrastructure.csproj`);
  const proj = readFileSync(csproj, 'utf8');
  if (!proj.includes(`Include="${name}"`)) {
    const at = /^([ \t]*)<PackageReference /m.exec(proj);
    if (!at) throw new Error(`${csproj}: <PackageReference> yok; ${name} eklenemedi.`);
    writeFileSync(csproj, `${proj.slice(0, at.index)}${at[1]}<PackageReference Include="${name}" />\n${proj.slice(at.index)}`);
  }
}

function addEnvKeys(root: string, modules: readonly AuthModule[]): void {
  const path = join(root, '.env.example');
  if (!existsSync(path)) return;
  const text = readFileSync(path, 'utf8');
  const lines = [
    'Jwt__AccessTtlMinutes=15',
    'Jwt__RefreshTtlDays=30',
    'Auth__RateLimitPerMinute=10',
    ...modules.flatMap((m) => DOTNET_MODULE_ENV[m] ?? []),
    ...(authUsesMail(modules) ? DOTNET_MAIL_ENV : [])
  ].filter((line) => !new RegExp(`^${line.split('=')[0]}=`, 'm').test(text));
  if (!lines.length) return;
  const block = ['', '# Auth (docs/backend/auth.md). Smtp__Host boşsa e-postalar log\'a yazılır.', ...lines, ''];
  writeFileSync(path, `${text.replace(/\n*$/, '\n')}${block.join('\n')}`);
}

export function bootstrapDotnetAuth(root: string, app: string, db: HostDatabase, modules: readonly AuthModule[], admin: AuthSeedAdmin): { files: WrittenFile[] } {
  const dir = authDir();
  const provider = db.database === 'mongodb' ? 'mongodb' : 'relational';
  const layout = dotnetLayout(root, app);
  const files: WrittenFile[] = [];
  for (const layer of DOTNET_LAYERS) {
    const tree = collect([join(dir, layer), join(dir, 'providers', provider, layer)]);
    for (const [rel, file] of [...tree.entries()].sort(([a], [b]) => a.localeCompare(b))) {
      const content = render(file, app, modules);
      if (content !== null) files.push(writeOnce(join(layout.projectDir(layer), applyAppTokens(rel, app)), content));
    }
  }
  // Skeleton replacements: the host was created a moment ago, these files are still the skeleton's.
  for (const [rel, file] of collect([join(dir, '_skeleton')])) {
    const content = render(file, app, modules);
    if (content === null) continue;
    const target = join(root, applyAppTokens(rel, app));
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    files.push({ path: target, action: 'updated' });
  }
  files.push(writeOnce(join(layout.projectDir('Infrastructure'), 'Auth', 'InitialAdmin.cs'), initialAdminFile(app, admin)));
  addBcryptPackage(root, app);
  addEnvKeys(root, modules);
  return { files };
}
