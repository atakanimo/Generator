/**
 * Python + FastAPI host layout (plan backend-python-fastapi §2): package name, folders and G file paths in one place.
 */
import { join } from 'path';

/** Token in skeleton paths / contents; replaced by the package name (snake_case, e.g. `alpha_terminal`). */
export const PY_APP_TOKEN = '__app__';
/** Distribution name token (`pyproject.toml` `[project].name`, kebab-case, e.g. `alpha-terminal`). */
export const PY_DIST_TOKEN = '__app_dist__';

/** First line of every G file (K7); a file without it is user-owned. */
export const PYTHON_GENERATED_HEADER = '# <auto-generated by Generator />';

export const PYTHON_KEYWORDS = new Set([
  'false', 'none', 'true', 'and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif',
  'else', 'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or',
  'pass', 'raise', 'return', 'try', 'while', 'with', 'yield', 'match', 'case', 'type'
]);

/** `AlphaTerminal`, `alpha-terminal`, `alpha terminal` → `alpha_terminal`. */
export function toPythonPackageName(name: string): string {
  return name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();
}

export function isValidPythonPackage(pkg: string): boolean {
  return /^[a-z][a-z0-9_]*$/.test(pkg) && !pkg.endsWith('_') && !PYTHON_KEYWORDS.has(pkg);
}

export function pythonDistName(pkg: string): string {
  return pkg.replace(/_/g, '-');
}

export interface PythonLayout {
  pkg: string;
  root: string;
  /** `src/<pkg>` */
  packageDir: string;
  /** `src/<pkg>/core` (asset target) */
  coreDir: string;
  /** `src/<pkg>/api/routers_generated.py` (G registry) */
  routersRegistry: string;
  /** `src/<pkg>/api/indexes_generated.py` (G registry: module repositories, `ensure_crud_indexes`) */
  indexesRegistry: string;
}

export function pythonLayout(root: string, pkg: string): PythonLayout {
  const packageDir = join(root, 'src', pkg);
  return {
    pkg,
    root,
    packageDir,
    coreDir: join(packageDir, 'core'),
    routersRegistry: join(packageDir, 'api', 'routers_generated.py'),
    indexesRegistry: join(packageDir, 'api', 'indexes_generated.py')
  };
}
