/**
 * Shared auth layer for a new Python host (docs/backend/auth.md). Runs right after the skeleton:
 *
 * - `src/generator-assets/python-fastapi/auth/**` → host, create-only (K). Module conditions (`# @auth-file`, `# @if`)
 *   keep only the picked modules (`applyAuthBlocks`). Tokens as in the skeleton (`__app__`), plus `__App__` (app name).
 * - `src/<pkg>/seed/initial_admin.py`: first admin (bcrypt hash only).
 * - `pyproject.toml`: `PyJWT[crypto]` when Google / Apple is on (RS256 + JWKS).
 * - `.env.example`: the picked modules' keys.
 *
 * The `Users` model is a normal manifest row, generated by the caller (`bootstrapPythonProject`).
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join, relative } from 'path';
import { AUTH_MAIL_ENV, AUTH_MODULE_INFO, authUsesMail, type AuthModule } from '../../../shared/authModules.js';
import { applyAuthBlocks } from '../../utils/authBlocks.js';
import type { AuthSeedAdmin } from '../../utils/authSeed.js';
import { WrittenFile, listFiles, writeOnce } from '../dotnet-efcore/dotnetFiles.js';
import { applyPythonTokens, pythonAssetsDir } from './pythonFiles.js';

const APP_NAME_TOKEN = '__App__';

/**
 * Removing module blocks leaves the blank lines ruff put around them: at most two blank lines in a row, one newline at
 * the end, and no blank line between two first-party imports (ruff isort keeps one block per section).
 */
export function tidyPython(text: string, pkg: string): string {
  const firstParty = (line: string) => line.startsWith(`from ${pkg}.`) || line.startsWith(`from ${pkg} `) || line.startsWith(`import ${pkg}`);
  const lines = text.split('\n');
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === '') {
      const prev = out[out.length - 1];
      let j = i;
      while (j < lines.length && lines[j].trim() === '') j++;
      // A parenthesised import ends with `)`: look back to its `from` line.
      let k = out.length - 1;
      while (k >= 0 && (out[k].startsWith('    ') || out[k] === ')')) k--;
      if (prev !== undefined && k >= 0 && firstParty(out[k]) && j < lines.length && firstParty(lines[j])) {
        i = j - 1;
        continue;
      }
      if (out.length >= 2 && out[out.length - 1].trim() === '' && out[out.length - 2].trim() === '') continue;
    }
    out.push(line);
  }
  return `${out.join('\n').replace(/\s*$/, '')}\n`;
}

function initialAdminFile(admin: AuthSeedAdmin): string {
  return [
    '"""İlk admin (docs/backend/auth.md "İlk admin"): Generator yazdı, yalnız bcrypt hash\'ini tutar.',
    '',
    'Açılışta hiç `admin` kullanıcı yoksa bu kayıt oluşturulur; sonra bir daha okunmaz.',
    '"""',
    '',
    'from __future__ import annotations',
    '',
    'INITIAL_ADMIN: dict[str, str] = {',
    `    "email": ${JSON.stringify(admin.email)},`,
    `    "name": ${JSON.stringify(admin.name)},`,
    `    "passwordHash": ${JSON.stringify(admin.passwordHash)},`,
    '}',
    ''
  ].join('\n');
}

function addEnvKeys(root: string, modules: readonly AuthModule[]): void {
  const path = join(root, '.env.example');
  if (!existsSync(path)) return;
  const text = readFileSync(path, 'utf8');
  const keys = [...modules.flatMap((m) => AUTH_MODULE_INFO[m].env), ...(authUsesMail(modules) ? AUTH_MAIL_ENV : [])].filter(
    (k) => !new RegExp(`^${k}=`, 'm').test(text)
  );
  if (!keys.length) return;
  const lines = ['# Auth modülleri (docs/backend/auth.md). SMTP_HOST boşsa e-postalar log\'a yazılır.', ...keys.map((k) => `${k}=`), ''];
  writeFileSync(path, `${text.replace(/\n*$/, '\n')}${lines.join('\n')}`);
}

function addCryptoExtra(root: string, modules: readonly AuthModule[]): void {
  if (!modules.includes('google') && !modules.includes('apple')) return;
  const path = join(root, 'pyproject.toml');
  const text = readFileSync(path, 'utf8');
  if (text.includes('"PyJWT[crypto]')) return;
  writeFileSync(path, text.replace('"PyJWT>=', '"PyJWT[crypto]>='));
}

export function bootstrapPythonAuth(root: string, app: string, pkg: string, modules: readonly AuthModule[], admin: AuthSeedAdmin): { files: WrittenFile[] } {
  const dir = join(pythonAssetsDir(), 'auth');
  const files: WrittenFile[] = [];
  for (const file of listFiles(dir).filter((f) => !/[\\/]__pycache__[\\/]|\.pyc$/.test(f))) {
    const content = applyAuthBlocks(readFileSync(file, 'utf8'), modules);
    if (content === null) continue;
    const target = join(root, applyPythonTokens(relative(dir, file), pkg));
    files.push(writeOnce(target, tidyPython(applyPythonTokens(content, pkg).split(APP_NAME_TOKEN).join(app), pkg)));
  }
  files.push(writeOnce(join(root, 'src', pkg, 'seed', 'initial_admin.py'), initialAdminFile(admin)));
  addCryptoExtra(root, modules);
  addEnvKeys(root, modules);
  return { files };
}
